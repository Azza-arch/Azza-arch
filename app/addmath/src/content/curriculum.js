export function chapterById(id) { return CURRICULUM.find((c) => c.id === id) || null; }
export function learningStandardExists(chapterId, code) {
  const c = chapterById(chapterId);
  return !!c && c.contentStandards.some((s) => s.learningStandards.includes(code));
}
